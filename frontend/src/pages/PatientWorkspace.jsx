import { useState, useEffect, useCallback } from 'react';
import { useParams } from 'react-router-dom';
import {
  getPatient,
  listAssessments,
  listLabs,
  listMedications,
  listPatientFindings,
  getPatientTimeline,
  updateMedication,
  listPatientImages,
  listPatientDocuments,
} from '../api/patients';
import PatientHeader from '../components/patient/PatientHeader';
import Tabs from '../components/common/Tabs';
import OverviewTab from '../components/patient/OverviewTab';
import ClinicalTrendsTab from '../components/patient/ClinicalTrendsTab';
import AssessmentTab from '../components/patient/AssessmentTab';
import LabsTab from '../components/patient/LabsTab';
import MedicationsTab from '../components/patient/MedicationsTab';
import MedicalImagesTab from '../components/patient/MedicalImagesTab';
import MedicalDocumentsTab from '../components/patient/MedicalDocumentsTab';
import TimelineTab from '../components/patient/TimelineTab';
import ReportsTab from '../components/patient/ReportsTab';
import NewAssessmentModal from '../components/patient/NewAssessmentModal';
import AddLabModal from '../components/patient/AddLabModal';
import AddMedicationModal from '../components/patient/AddMedicationModal';
import ScheduleFollowUpModal from '../components/patient/ScheduleFollowUpModal';
import ReviewFindingModal from '../components/patient/ReviewFindingModal';
import EditPatientModal from '../components/patient/EditPatientModal';
import InlineAlert from '../components/common/InlineAlert';

const TABS = [
  { key: 'overview', label: 'Clinical Overview' },
  { key: 'trends', label: 'Clinical Trends' },
  { key: 'assessment', label: 'Assessments' },
  { key: 'labs', label: 'Laboratory Results' },
  { key: 'medications', label: 'Medications' },
  { key: 'images', label: 'Medical Images' },
  { key: 'documents', label: 'Medical Documents' },
  { key: 'timeline', label: 'Timeline' },
  { key: 'reports', label: 'Summary Report' },
];

export default function PatientWorkspace() {
  const { id } = useParams();
  const [activeTab, setActiveTab] = useState('overview');
  const [patient, setPatient] = useState(null);
  const [overview, setOverview] = useState(null);
  const [assessments, setAssessments] = useState([]);
  const [labs, setLabs] = useState([]);
  const [medications, setMedications] = useState([]);
  const [findings, setFindings] = useState([]);
  const [images, setImages] = useState([]);
  const [documents, setDocuments] = useState([]);
  const [timeline, setTimeline] = useState([]);
  const [loading, setLoading] = useState(true);
  const [banner, setBanner] = useState(null);

  const [modal, setModal] = useState(null); // 'assessment' | 'lab' | 'medication' | 'followup' | 'edit' | { review: finding }

  const loadAll = useCallback(async () => {
    setLoading(true);
    try {
      const [
        patientRes,
        assessmentsRes,
        labsRes,
        medsRes,
        findingsRes,
        timelineRes,
        imagesRes,
        docsRes,
      ] = await Promise.all([
        getPatient(id),
        listAssessments(id),
        listLabs(id),
        listMedications(id),
        listPatientFindings(id),
        getPatientTimeline(id),
        listPatientImages(id).catch(() => []),
        listPatientDocuments(id).catch(() => []),
      ]);

      setPatient(patientRes.patient);
      setOverview(patientRes.overview);
      setAssessments(assessmentsRes);
      setLabs(labsRes);
      setMedications(medsRes);
      setFindings(findingsRes);
      setTimeline(timelineRes);
      setImages(imagesRes);
      setDocuments(docsRes);
    } catch (err) {
      console.error('Failed to load patient records:', err);
    } finally {
      setLoading(false);
    }
  }, [id]);

  useEffect(() => {
    loadAll();
  }, [loadAll]);

  function showBanner(findingsGenerated) {
    if (findingsGenerated && findingsGenerated.length > 0) {
      setBanner(
        `${findingsGenerated.length} new clinical finding${
          findingsGenerated.length > 1 ? 's' : ''
        } generated by CDS engine — clinician review required.`
      );
    } else {
      setBanner(null);
    }
    setTimeout(() => setBanner(null), 7000);
  }

  async function handleDiscontinue(med) {
    await updateMedication(id, med._id, { status: 'Discontinued', endDate: new Date().toISOString() });
    loadAll();
  }

  if (loading || !patient) return <div className="muted" style={{ padding: 24 }}>Loading clinical patient workspace...</div>;

  return (
    <div>
      {banner && <InlineAlert tone="warning">{banner}</InlineAlert>}

      <PatientHeader
        patient={patient}
        overview={overview}
        onNewAssessment={() => setModal('assessment')}
        onAddLab={() => setModal('lab')}
        onAddMedication={() => setModal('medication')}
        onScheduleFollowUp={() => setModal('followup')}
        onEditPatient={() => setModal('edit')}
        onPrintReport={() => setActiveTab('reports')}
      />

      <Tabs tabs={TABS} active={activeTab} onChange={setActiveTab} />

      {activeTab === 'overview' && (
        <OverviewTab
          patient={patient}
          overview={overview}
          onReviewFinding={(f) => setModal({ review: f })}
        />
      )}

      {activeTab === 'trends' && (
        <ClinicalTrendsTab assessments={assessments} labs={labs} />
      )}

      {activeTab === 'assessment' && <AssessmentTab assessments={assessments} />}

      {activeTab === 'labs' && <LabsTab labs={labs} />}

      {activeTab === 'medications' && (
        <MedicationsTab medications={medications} onDiscontinue={handleDiscontinue} />
      )}

      {activeTab === 'images' && <MedicalImagesTab images={images} />}

      {activeTab === 'documents' && <MedicalDocumentsTab documents={documents} patient={patient} />}

      {activeTab === 'timeline' && <TimelineTab events={timeline} />}

      {activeTab === 'reports' && (
        <ReportsTab
          patient={patient}
          assessments={assessments}
          labs={labs}
          medications={medications}
          findings={findings}
        />
      )}

      {modal === 'assessment' && (
        <NewAssessmentModal
          patientId={id}
          onClose={() => setModal(null)}
          onCreated={(res) => {
            showBanner(res.findingsGenerated);
            loadAll();
          }}
        />
      )}

      {modal === 'lab' && (
        <AddLabModal
          patientId={id}
          onClose={() => setModal(null)}
          onCreated={(res) => {
            showBanner(res.findingsGenerated);
            loadAll();
          }}
        />
      )}

      {modal === 'medication' && (
        <AddMedicationModal
          patientId={id}
          onClose={() => setModal(null)}
          onCreated={(res) => {
            showBanner(res.findingsGenerated);
            loadAll();
          }}
        />
      )}

      {modal === 'followup' && (
        <ScheduleFollowUpModal
          patientId={id}
          onClose={() => setModal(null)}
          onCreated={() => loadAll()}
        />
      )}

      {modal === 'edit' && (
        <EditPatientModal
          patient={patient}
          onClose={() => setModal(null)}
          onUpdated={() => loadAll()}
        />
      )}

      {modal && modal.review && (
        <ReviewFindingModal
          finding={modal.review}
          onClose={() => setModal(null)}
          onReviewed={() => loadAll()}
        />
      )}
    </div>
  );
}
