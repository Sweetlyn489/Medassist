import { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { listFindings } from '../api/findings';
import DataTable from '../components/common/DataTable';
import StatusBadge from '../components/common/StatusBadge';
import ReviewFindingModal from '../components/patient/ReviewFindingModal';

function formatDate(d) {
  return d ? new Date(d).toLocaleString() : '—';
}

export default function Findings() {
  const [findings, setFindings] = useState([]);
  const [status, setStatus] = useState('Open');
  const [severity, setSeverity] = useState('');
  const [loading, setLoading] = useState(true);
  const [reviewTarget, setReviewTarget] = useState(null);
  const navigate = useNavigate();

  async function load() {
    setLoading(true);
    const res = await listFindings({ status: status || undefined, severity: severity || undefined });
    setFindings(res.data);
    setLoading(false);
  }

  useEffect(() => {
    load();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [status, severity]);

  return (
    <div>
      <div className="page-header">
        <h1>Clinical Findings</h1>
      </div>
      <p className="muted small" style={{ marginTop: -10, marginBottom: 14 }}>
        Findings are decision-support cues generated by configurable rules. They require clinical review, not automatic action.
      </p>

      <div className="toolbar">
        <select style={{ padding: '7px 10px', border: '1px solid var(--border)', borderRadius: 5, fontSize: 13.5 }} value={status} onChange={(e) => setStatus(e.target.value)}>
          <option value="">All statuses</option>
          <option value="Open">Open</option>
          <option value="Reviewed">Reviewed</option>
          <option value="Resolved">Resolved</option>
        </select>
        <select style={{ padding: '7px 10px', border: '1px solid var(--border)', borderRadius: 5, fontSize: 13.5 }} value={severity} onChange={(e) => setSeverity(e.target.value)}>
          <option value="">All severities</option>
          <option value="High">High</option>
          <option value="Moderate">Moderate</option>
          <option value="Low">Low</option>
        </select>
      </div>

      {loading ? (
        <div className="muted">Loading findings...</div>
      ) : (
        <DataTable
          emptyMessage="No findings match these filters."
          columns={[
            { key: 'patient', header: 'Patient', render: (r) => `${r.patient.firstName} ${r.patient.lastName} (${r.patient.patientId})` },
            { key: 'finding', header: 'Finding' },
            { key: 'severity', header: 'Severity', render: (r) => <StatusBadge value={r.severity} /> },
            { key: 'sourceType', header: 'Source' },
            { key: 'createdDate', header: 'Created', render: (r) => formatDate(r.createdDate) },
            { key: 'status', header: 'Status', render: (r) => <StatusBadge value={r.status} /> },
            {
              key: 'actions',
              header: '',
              render: (r) =>
                r.status === 'Open' ? (
                  <button className="btn btn-sm" onClick={(e) => { e.stopPropagation(); setReviewTarget(r); }}>Review</button>
                ) : (
                  <span className="muted small">by {r.reviewedBy?.name || '—'}</span>
                ),
            },
          ]}
          rows={findings}
          onRowClick={(row) => navigate(`/patients/${row.patient._id}`)}
        />
      )}

      {reviewTarget && (
        <ReviewFindingModal
          finding={reviewTarget}
          onClose={() => setReviewTarget(null)}
          onReviewed={() => load()}
        />
      )}
    </div>
  );
}
